-- Run once on databases that already have AUTH_OTP_CHALLENGE.
IF OBJECT_ID('AUTH_OTP_CHALLENGE', 'U') IS NOT NULL
   AND COL_LENGTH('AUTH_OTP_CHALLENGE', 'verified') IS NULL
BEGIN
    ALTER TABLE AUTH_OTP_CHALLENGE
    ADD verified BIT NOT NULL
        CONSTRAINT DF_AUTH_OTP_VERIFIED DEFAULT 0;
END;
GO
